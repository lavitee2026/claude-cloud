def load(nid):
    t = (ART / f'{nid}.md').read_text(encoding='utf-8')
    meta = dict(re.findall(r'^(\w+): (.*)$', t.split('\n---\n', 1)[0], re.M))
    body = t.split('\n---\n', 1)[1]
    def section(name):
        m = re.search(rf'^## {name}\n\n(.*?)(?=\n## |\n::: |\Z)', body, re.S | re.M)
        return m.group(1).strip() if m else ''
    qs = re.findall(r'^\d+\. (.+)$', section('面诊时可以问的问题'), re.M)
    return meta, qs, section('今天能做的一件事')

